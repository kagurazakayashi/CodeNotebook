#!/bin/bash

###############################################################################
# Mastodon 每日清理脚本
#
# 功能：
#   1. 删除超过 7 天的远程帖子媒体附件
#   2. 删除超过 7 天的远程账号头像和 Header 缓存
#   3. 删除超过 30 天的网页预览卡片（Preview Card）
#   4. 删除超过 7 天的用户导出备份
#
# 注意：
#   - 不删除本站用户上传的正常媒体
#   - 不删除远程帖子正文
#   - 不使用 --include-follows，因此保护存在关注关系的远程账号 Profile
#   - Backup 清理由 Mastodon 自己的 Vacuum::BackupsVacuum 实现
#
# 日志：
#   /var/log/yashi/mastodonclean.log
###############################################################################

set -u

# Mastodon Web 容器名称
CONTAINER="mastodon-web-1"

# 日志目录和日志文件
LOG_DIR="/var/log/yashi"
LOG_FILE="${LOG_DIR}/mastodonclean.log"

# 所有 Mastodon 清理脚本共用同一个锁文件。
# 防止每日、每周、每月任务意外同时执行。
LOCK_FILE="/run/lock/mastodon-clean.lock"

mkdir -p "$LOG_DIR"


###############################################################################
# 获取执行锁
###############################################################################

exec 9>"$LOCK_FILE"

if ! flock -n 9; then
    echo "$(date '+%Y-%m-%d %H:%M:%S') [每日清理] 检测到已有 Mastodon 清理任务正在运行，本次任务跳过。" >> "$LOG_FILE"
    exit 0
fi


###############################################################################
# 从这里开始，将标准输出和错误输出全部追加到日志文件
###############################################################################

exec >> "$LOG_FILE" 2>&1


###############################################################################
# 用于记录本次任务是否出现失败
#
# 我们故意不使用 set -e：
# 即使其中一个清理步骤失败，也继续执行后面的步骤，并在最后返回失败状态。
###############################################################################

FAILED=0


###############################################################################
# 通用命令执行函数
###############################################################################

run_command() {
    echo
    echo "----------------------------------------------------------------------"
    echo "开始执行：$*"
    echo "开始时间：$(date '+%Y-%m-%d %H:%M:%S')"
    echo "----------------------------------------------------------------------"

    "$@"
    RC=$?

    if [ "$RC" -eq 0 ]; then
        echo "执行结果：成功"
    else
        echo "执行结果：失败"
        echo "退出代码：$RC"
        FAILED=1
    fi

    echo "完成时间：$(date '+%Y-%m-%d %H:%M:%S')"
}


###############################################################################
# 每日清理开始
###############################################################################

echo
echo
echo "======================================================================"
echo "              Mastodon 每日自动清理开始"
echo "======================================================================"
echo "时间：$(date '+%Y-%m-%d %H:%M:%S')"
echo "容器：${CONTAINER}"
echo
echo "本次清理策略："
echo "  - 远程帖子媒体附件：保留 7 天"
echo "  - 远程头像 / Header：保留 7 天"
echo "  - Preview Card：保留 30 天"
echo "  - 用户导出 Backup：保留 7 天"
echo "======================================================================"


###############################################################################
# 0. 清理前输出当前媒体使用情况
###############################################################################

echo
echo "【0/5】清理前媒体使用情况"

run_command \
    docker exec \
    -e RAILS_ENV=production \
    "$CONTAINER" \
    bin/tootctl media usage


###############################################################################
# 1. 清理远程帖子媒体附件
#
# 这里只处理从其他实例缓存过来的帖子图片、视频等媒体。
#
# --days 7
#   删除超过 7 天的远程媒体缓存。
###############################################################################

echo
echo "【1/5】清理超过 7 天的远程帖子媒体附件"

run_command \
    docker exec \
    -e RAILS_ENV=production \
    "$CONTAINER" \
    bin/tootctl media remove \
    --days 7


###############################################################################
# 2. 清理远程账号头像和 Header
#
# 这是你的实例之前最主要的 R2 空间占用来源。
#
# --prune-profiles
#   处理远程账号的 Avatar 和 Header。
#
# 不加入：
#
#   --include-follows
#
# 因此 Mastodon 会继续保护与本站用户存在关注关系的远程账号 Profile。
###############################################################################

echo
echo "【2/5】清理超过 7 天的远程头像和 Header"

run_command \
    docker exec \
    -e RAILS_ENV=production \
    "$CONTAINER" \
    bin/tootctl media remove \
    --prune-profiles \
    --days 7


###############################################################################
# 3. 清理 Preview Card
#
# Preview Card 是帖子中的网页链接预览图片和相关缓存。
#
# 保留 30 天。
###############################################################################

echo
echo "【3/5】清理超过 30 天的 Preview Card"

run_command \
    docker exec \
    -e RAILS_ENV=production \
    "$CONTAINER" \
    bin/tootctl preview_cards remove \
    --days 30


###############################################################################
# 4. 清理用户生成的导出 Backup
#
# 因为 backups_retention_period=nil，
# Mastodon 自带定期 retention 不再负责这个工作。
#
# 这里直接调用 Mastodon 自己内部的 BackupsVacuum。
#
# 只删除创建时间超过 7 天的 Backup。
###############################################################################

echo
echo "【4/5】清理超过 7 天的用户导出 Backup"

run_command \
    docker exec \
    -e RAILS_ENV=production \
    "$CONTAINER" \
    bin/rails runner \
    'puts "开始清理超过 7 天的 Backup..."; Vacuum::BackupsVacuum.new(7.days).perform; puts "Backup 清理完成。"'


###############################################################################
# 5. 清理后重新统计媒体使用情况
###############################################################################

echo
echo "【5/5】清理完成后的媒体使用情况"

run_command \
    docker exec \
    -e RAILS_ENV=production \
    "$CONTAINER" \
    bin/tootctl media usage


###############################################################################
# 每日清理结束
###############################################################################

echo
echo "======================================================================"

if [ "$FAILED" -eq 0 ]; then
    echo "Mastodon 每日自动清理完成：全部任务执行成功"
else
    echo "Mastodon 每日自动清理完成：存在失败任务，请检查上方日志"
fi

echo "结束时间：$(date '+%Y-%m-%d %H:%M:%S')"
echo "======================================================================"
echo

exit "$FAILED"
